"""Generate the BICYCLE_CONFIG block of hw/hls/source/include/config.hpp and the constants of
models/hls_bicycle.hpp from the RC car parameter files (C level only; no synthesis).

    python3 app/rc_car/gen_bicycle_config.py            # print both blocks
    python3 app/rc_car/gen_bicycle_config.py --check    # exit 1 if the files differ from the generator
    python3 app/rc_car/gen_bicycle_config.py --write    # (re)write the generated blocks in place

Sources (read at generation time, nothing typed by hand):
- params/reely_new1.yaml: wheelbase L, delta_max, v_max_sim  ->  kappa_max = tan(delta_max) / L;
- params/command_chain.yaml (vehicle_limits_profile): accel/decel and steering-rate bounds -> du_max;
- params/nmpc.yaml: Nh, Ts, the frozen section 9.3 weights and the `redesign_smooth` switches
  (the accepted candidate: R1 + R2 (5 knots) + R3 (3160, 316) + R4 (s_dkappa 10)).
All of these are SIMULATION values: delta_max is measured_approx, L spec_unverified, the rate and
acceleration bounds PLACEHOLDER_ guesses (see the yaml files). Regenerate after every measurement.

The edit to config.hpp is a pure addition: the BICYCLE_CONFIG block goes before the `#endif` that
closes the model chain, and the redesign-switch block after it. No existing line changes
(gen_headers.sh in arc-shared-rollout checks this with `diff | grep '^<'`).
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path
import re
import sys

import numpy as np
import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import nmpc_controller as nc  # noqa: E402
import nmpc_engine as ne  # noqa: E402
from nmpc_engine import am  # noqa: E402

REPO = HERE.parents[1]
CONFIG = REPO / "hw/hls/source/include/config.hpp"
MODEL = REPO / "hw/hls/source/include/models/hls_bicycle.hpp"
CFG_BEGIN = "#elif defined(BICYCLE_CONFIG)"
CFG_END = "    // END BICYCLE_CONFIG (generated by app/rc_car/gen_bicycle_config.py)"
RD_BEGIN = "// BEGIN PSO redesign switches (generated by app/rc_car/gen_bicycle_config.py)"
RD_END = "// END PSO redesign switches"
MODEL_BEGIN = "    // BEGIN generated constants (app/rc_car/gen_bicycle_config.py)"
MODEL_END = "    // END generated constants"
PERTURB_STD = 0.25  # nmpc_engine.Problem.perturb_scale: std of the R1 perturbation / rate window


def values(section: str = "redesign_smooth") -> dict:
    cfg = nc.load_config()
    rd = nc.load_redesign(section=section)
    lim, w = cfg.limits, cfg.weights
    vh = 0.5 * (lim.v_max - lim.v_min)
    kmax = lim.kappa_max
    du = am.normalized_slew_limits(lim, cfg.ts, ne.SCALE)
    s_dkappa = float(rd.r4) if rd.r4 is not None else w.s_dkappa
    ratio = w.qf_pos / w.q_pos
    knots = ne.make_knots(int(rd.r2), cfg.nh) if rd.r2 else None
    return {
        "section": section, "redesign": rd, "nh": cfg.nh, "nu": cfg.nu, "ts": cfg.ts,
        "L": cfg.wheelbase, "delta_max": cfg.delta_max, "v_min": lim.v_min, "v_max": lim.v_max, "kappa_max": kmax,
        "v_per_unit": (lim.v_max - lim.v_min) / (2 * ne.SCALE), "kappa_per_unit": kmax / ne.SCALE,
        "du": du, "weights": w,
        "Q": (w.q_pos, w.q_pos, w.q_psi), "Qf": (w.qf_pos, w.qf_pos, w.qf_psi),
        # section 9.3 effort terms in normalized units: (v - v_ref)^2 = (vh/100)^2 (z - z_ref)^2
        "R": (w.q_v * (vh / ne.SCALE) ** 2, w.r_kappa * (kmax / ne.SCALE) ** 2),
        "Wr": (math.sqrt(w.q_v) * vh / ne.SCALE, math.sqrt(w.r_kappa) * kmax / ne.SCALE),
        "Ws": (math.sqrt(w.s_dv) * vh / ne.SCALE, math.sqrt(s_dkappa) * kmax / ne.SCALE),
        "s_dkappa": s_dkappa,
        "Q_pf": tuple(rd.r3) if rd.r3 else None, "Qf_pf": tuple(ratio * q for q in rd.r3) if rd.r3 else None,
        "knots": knots,
    }


def _fmt(x: float) -> str:
    return repr(float(x))


def config_block(v: dict) -> str:
    rd, w = v["redesign"], v["weights"]
    nh = v["nh"]
    lines = [
        CFG_BEGIN,
        "",
        "    // Kinematic bicycle (RC car, Reely NEW1 in Gazebo): state [x (m), y (m), psi (rad)], control [v, kappa]",
        "    // normalized to +-100 (models/hls_bicycle.hpp maps them to m/s and 1/m by multiplications).",
        "    // GENERATED by app/rc_car/gen_bicycle_config.py from app/rc_car/params/{reely_new1,command_chain,nmpc}.yaml;",
        "    // do not edit by hand. SIMULATION VALUES: L = %s m (spec_unverified), delta_max = %s rad" % (_fmt(v["L"]), _fmt(v["delta_max"])),
        "    // (measured_approx) -> kappa_max = tan(delta_max)/L = %.9g 1/m; v in [%g, %g] m/s (v_max_sim, design);" % (v["kappa_max"], v["v_min"], v["v_max"]),
        "    // the rate bounds are PLACEHOLDER_ guesses (command_chain.yaml realistic_guess).",
        "    // Without the PSO_RD_* switches this is a Stage A engine (diagonal Q/R about _uss, RK4), which was",
        "    // never run in the closed loop; the simulated controller is the section 9.3 cost = PSO_RD_UREF + PSO_RD_R4.",
        "    #define _Nh %d" % nh,
        "#ifdef PSO_RD_R2",
        "    #define _Nu %d      // R2: the decision is %d knots per input (stages %s), interpolated over _Nh" % (len(v["knots"]), len(v["knots"]), ", ".join(map(str, v["knots"]))),
        "#else",
        "    #define _Nu %d      // = _Nh (the ARC engine reads u_k as cg[p][k*n_U + j])" % v["nu"],
        "#endif",
        "    #define _Nx 3",
        "    #define _n_U 2",
        "    const _hw_top_real  _Ts = %s;" % _fmt(v["ts"]),
        "    const _hw_top_real  _u_max[] =  {100, 100};",
        "    const _hw_top_real  _u_min[] =  {-100, -100};",
        "    // du_max = 100 min(accel, decel) Ts / v_h and 100 kappa_rate_max Ts / kappa_max (normalized_slew_limits)",
        "    const _hw_top_real  _du_max[] =  {",
        "        %s," % _fmt(v["du"][0]),
        "        %s" % _fmt(v["du"][1]),
        "    };",
        "    // z_v(v = 0) = -100 (v_min = 0), kappa 0: the stable-zero particle is the brake candidate",
        "    const _hw_top_real  _uss[] = {-100.0, 0.0};",
        "",
        "    #define  _Parametrization 0",
        "    // Not used by the evaluator; mirrored from the quadrotor block so code naming them compiles.",
        "    const _hw_top_real  _Lambda = 5;",
        "    const _hw_top_real  _q_param = 2;",
        "    const _hw_top_real  _pmax[] =  {1, 1};",
        "    const _hw_top_real  _pmin[] =  {-1, -1};",
        "",
        "    // psi: wrapped residual (controlled_state 2); the host solves in the local frame (x0 = y0 = psi0 = 0).",
        "    const unsigned short _controlled_state[] = {1, 1, 2};",
        "    const _hw_top_real  _state_upper_limits[_Nx] =  {1e3, 1e3, 1e3};",
        "    const _hw_top_real  _state_lower_limits[_Nx] =  {-1e3, -1e3, -1e3};",
        "    // section 9.3 weights (params/nmpc.yaml, frozen 2026-11-22): q_pos %g, q_psi %g, terminal x %g" % (w.q_pos, w.q_psi, w.qf_pos / w.q_pos),
        "    const _hw_top_real  _Q[] =  {%s, %s, %s};" % tuple(_fmt(q) for q in v["Q"]),
        "    const _hw_top_real  _Qf[] =  {%s, %s, %s};" % tuple(_fmt(q) for q in v["Qf"]),
        "    // q_v (vh/100)^2 and r_kappa (kappa_max/100)^2 per normalized unit^2; about _uss, so only a Stage A",
        "    // stand-in. Both are a few LSB of ap_fixed<32,17> (2^-15): the redesign path uses _rd_Wr instead.",
        "    const _hw_top_real  _R[] =  {%s, %s};" % tuple(_fmt(r) for r in v["R"]),
        "",
        "    #define  _Rising_Time 0",
        "    const _hw_top_real _tr[] =  {0, 0, 0};",
        "",
        "#ifdef PSO_RD_ANY",
        "    // PSO redesign (2026-11-22 brief; accepted candidate = params/nmpc.yaml `%s`). Weights in" % v["section"],
        "    // square-root form: the cost adds (W e)^2, so a weight below the 2^-15 grid keeps its precision.",
        "    // PSO_RD_UREF: sqrt(q_v) v_h/100, sqrt(r_kappa) kappa_max/100 against the host's per-stage u_ref",
        "    const _hw_top_real  _rd_Wr[] = {%s, %s};" % tuple(_fmt(x) for x in v["Wr"]),
        "    // PSO_RD_R4: sqrt(s_dv) v_h/100, sqrt(s_dkappa) kappa_max/100 on u_k - u_{k-1} (u_{-1} = u_curr); s_dkappa = %g (R4)" % v["s_dkappa"],
        "    const _hw_top_real  _rd_Ws[] = {%s, %s};" % tuple(_fmt(x) for x in v["Ws"]),
        "    // PSO_RD_R3: lateral and along-track position weights (stage, terminal); replace _Q[0..1] / _Qf[0..1]",
        "    const _hw_top_real  _rd_Q_pf[] = {%s, %s};" % tuple(_fmt(x) for x in v["Q_pf"]),
        "    const _hw_top_real  _rd_Qf_pf[] = {%s, %s};" % tuple(_fmt(x) for x in v["Qf_pf"]),
        "    // PSO_RD_R1: perturbed copies of particle 0: max(1, n_S/5) for n_S >= 4, uniform noise of std",
        "    // %g x the rate window (the hardware stream is uniform: half-width %g x sqrt(3))" % (PERTURB_STD, PERTURB_STD),
        "    #define _rd_n_perturb ((_n_S >= 4) ? ((_n_S / 5 > 1) ? (_n_S / 5) : 1) : 0)",
        "    const _hw_top_real  _rd_perturb_frac = %s;" % _fmt(PERTURB_STD * math.sqrt(3.0)),
    ]
    k = v["knots"]
    gaps = np.diff(np.concatenate([[-1], k])).astype(int)
    W = ne.interp_matrix(k, nh)
    js = [int(min(np.searchsorted(k, h, side="right") - 1, len(k) - 2)) for h in range(nh)]
    a = [float(W[h, js[h] + 1]) for h in range(nh)]
    lines += [
        "#ifdef PSO_RD_R2",
        "    // knots at stages {%s}: per-knot rate window = du_max x gap; stage h uses knots j, j+1 with weight a" % ", ".join(map(str, k)),
        "    const _hw_top_real  _rd_knot_gap[_Nu] = {%s};" % ", ".join(str(g) for g in gaps),
        "    const unsigned char _rd_knot_j[_Nh] = {%s};" % ", ".join(map(str, js)),
        "    const _hw_top_real  _rd_knot_a[_Nh] = {%s};" % ", ".join(_fmt(x) for x in a),
        "#endif",
        "    // rd_aux buffer (one new top-level input, normalized units, written by the host each solve):",
        "    // [n_extra (0/1) | extra start (_Nu x _n_U) | u_ref (_Nh x _n_U) | cos, sin of psi_ref (_Nh x 2)]",
        "    #define _RD_AUX_NEXTRA 0",
        "    #define _RD_AUX_EXTRA 1",
        "    #define _RD_AUX_UREF (_RD_AUX_EXTRA + _Nu*_n_U)",
        "    #define _RD_AUX_CS (_RD_AUX_UREF + _Nh*_n_U)",
        "    #define _RD_AUX_LEN (_RD_AUX_CS + _Nh*2)",
        "#endif",
        CFG_END,
    ]
    return "\n".join(lines) + "\n"


def rd_block() -> str:
    return "\n".join([
        RD_BEGIN,
        "// Compile-time switches of the PSO redesign; all off = the sources before the redesign (byte-identical",
        "// outputs, checked by app/rc_car/hls_bicycle_check.py). Defined for BICYCLE_CONFIG only.",
        "//   PSO_RD_R1    warm start: extra start in particle 2 (host), perturbed copies of particle 0",
        "//   PSO_RD_R2    move blocking: _Nu knots per input, linear interpolation in the rollout input",
        "//   PSO_RD_R3    path-frame position cost with the host's per-stage cos/sin of psi_ref",
        "//   PSO_RD_R4    increment cost (u_k - u_{k-1})^2 with u_{-1} = u_curr (s_dkappa = the R4 weight)",
        "//   PSO_RD_UREF  effort about the host's per-stage reference control instead of _uss (section 9.3)",
        "//   PSO_RD_ALL   all five (the simulated candidate controller)",
        "#ifdef PSO_RD_ALL",
        "#define PSO_RD_R1",
        "#define PSO_RD_R2",
        "#define PSO_RD_R3",
        "#define PSO_RD_R4",
        "#define PSO_RD_UREF",
        "#endif",
        "#if defined(PSO_RD_R1) || defined(PSO_RD_R2) || defined(PSO_RD_R3) || defined(PSO_RD_R4) || defined(PSO_RD_UREF)",
        "#define PSO_RD_ANY",
        "#ifndef BICYCLE_CONFIG",
        "#error \"the PSO_RD_* switches are defined for BICYCLE_CONFIG only\"",
        "#endif",
        "#endif",
        RD_END,
    ]) + "\n"


def model_constants(v: dict) -> str:
    return "\n".join([
        MODEL_BEGIN,
        "    // SIMULATION values: v in [%g, %g] m/s (v_max_sim), kappa_max = tan(%s)/%s = %.12g 1/m" % (
            v["v_min"], v["v_max"], _fmt(v["delta_max"]), _fmt(v["L"]), v["kappa_max"]),
        "    const _model_real v_min = %s;              // m/s" % _fmt(v["v_min"]),
        "    const _model_real z_v_min = -100;          // normalized control at v_min",
        "    const _model_real v_per_unit = %s;        // (v_max - v_min) / 200   [m/s per unit]" % _fmt(v["v_per_unit"]),
        "    const _model_real kappa_per_unit = %s; // kappa_max / 100   [1/m per unit]" % _fmt(v["kappa_per_unit"]),
        MODEL_END,
    ]) + "\n"


def _replace(text: str, begin: str, end: str, new: str, anchor_before: str | None) -> str:
    if begin in text:
        i = text.index(begin)
        j = text.index(end, i) + len(end) + 1
        return text[:i] + new + text[j:]
    if anchor_before is None:
        raise ValueError(f"{begin!r} not found")
    i = text.index(anchor_before)
    return text[:i] + new + text[i:]


def render_config(text: str, v: dict) -> str:
    # The chain's closing #endif is the first "#endif" line after the UNICYCLE block's _tr line.
    uni = text.index("#elif defined(UNICYCLE_CONFIG)")
    m = re.compile(r"^#endif\n", re.M).search(text, uni)
    if CFG_BEGIN not in text:
        text = text[:m.start()] + config_block(v) + text[m.start():]
    else:
        text = _replace(text, CFG_BEGIN, CFG_END, config_block(v), None)
    anchor = "#ifdef INVERTED_PENDULUM_CONFIG"  # before the model chain: the blocks test PSO_RD_*
    return _replace(text, RD_BEGIN, RD_END, rd_block() + "\n", anchor) if RD_BEGIN not in text else \
        _replace(text, RD_BEGIN, RD_END, rd_block(), None)


def render_model(text: str, v: dict) -> str:
    return _replace(text, MODEL_BEGIN, MODEL_END, model_constants(v), None)


def _read(path: Path) -> tuple[str, str]:
    """Text with LF line ends, and the file's own line end (config.hpp is CRLF): written back as it was."""
    raw = path.read_bytes().decode()
    eol = "\r\n" if "\r\n" in raw else "\n"
    return raw.replace("\r\n", "\n"), eol


def _write(path: Path, text: str, eol: str) -> None:
    path.write_bytes(text.replace("\n", eol).encode())


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--section", default="redesign_smooth")
    a = ap.parse_args(argv)
    v = values(a.section)
    if not (a.check or a.write):
        print(config_block(v) + "\n" + rd_block() + "\n" + model_constants(v))
        return 0
    (cfg_old, cfg_eol), (mdl_old, mdl_eol) = _read(CONFIG), _read(MODEL)
    cfg_new, mdl_new = render_config(cfg_old, v), render_model(mdl_old, v)
    if a.write:
        _write(CONFIG, cfg_new, cfg_eol)
        _write(MODEL, mdl_new, mdl_eol)
        print(f"wrote {CONFIG} and {MODEL}")
        return 0
    ok = cfg_new == cfg_old and mdl_new == mdl_old
    print("generated blocks match" if ok else "generated blocks DIFFER from the files: run --write")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
