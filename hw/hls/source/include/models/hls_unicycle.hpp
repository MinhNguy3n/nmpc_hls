#ifndef HLS_UNICYCLE_HPP
#define HLS_UNICYCLE_HPP

// Unicycle model for the PSO-NMPC evaluator (UNICYCLE_CONFIG): x' = v cos(psi), y' = v sin(psi),
// psi' = omega. Same structure as __model in hls_sniffbot.hpp, so System::one_step_prediction
// (RK4, hls_system.hpp) uses it unchanged: model note docs/husky_a300/unicycle_mpc_pso_model.md,
// variant A (sections 5.2, 5.4) and the HLS audit (section 8).
//
// - Controls arrive normalized to +-100 and are mapped to m/s and rad/s by multiplications only
//   (no division): v = v_min + (v_max - v_min)/200 * (z_v + 100), omega = omega_max/100 * z_omega.
//   This is the model note's v = v_c + v_h z_v/100 rearranged so that z_v = -100 gives v = 0
//   exactly in half precision (a stop command predicts standstill).
// - cos(psi) is local_sin(psi + pi/2), as in hls_sniffbot.hpp; local_cos is not used (model
//   note 5.6: with USE_FAST_SIN_COS it scales the angle twice).
// - Every #pragma HLS sits on its own line: the engine's pipelined copy is generated by deleting
//   the pragma lines (gen_headers.sh), and nothing else may differ.

#include "hls_arith_aux_functions.hpp"
#ifdef __SYNTHESIS__
#include "hls_math.h"
#include "ap_fixed.h"
using namespace hls;
#else
#include "math.h"
#endif

template <
    typename _model_real
>void __model(
    volatile _model_real *state_dot, // [3]
    volatile _model_real *state,     // [3]
    volatile _model_real *control    // [2]
){

#pragma HLS interface mode=ap_fifo port=state_dot   depth=3
#pragma HLS interface mode=ap_fifo port=state       depth=3
#pragma HLS interface mode=ap_fifo port=control     depth=2

    // PROVISIONAL normalization: the A300 Gazebo SIL envelope v in [0, 0.3] m/s, |omega| <= 0.75
    // rad/s (sil/controller.py CoreConfig, model note 7.4). Not an A200 or robot value.
    const _model_real v_min = 0.0;             // m/s
    const _model_real z_v_min = -100;          // normalized control at v_min
    const _model_real v_per_unit = 0.0015;     // (v_max - v_min) / 200 = 0.3 / 200   [m/s per unit]
    const _model_real omega_per_unit = 0.0075; // omega_max / 100 = 0.75 / 100          [rad/s per unit]
    const _model_real local_pi_half = 1.57079632679;

#pragma HLS allocation operation instances=hmul limit=4
#pragma HLS allocation operation instances=hadd limit=2
#pragma HLS allocation operation instances=hsub limit=2

    _model_real psi, v, omega, cos_psi, sin_psi;

    psi = state[2];
    v = v_min + v_per_unit * (control[0] - z_v_min);
    omega = omega_per_unit * control[1];

    cos_psi = local_sin<_model_real>(psi + (_model_real)local_pi_half);
    sin_psi = local_sin<_model_real>(psi);

    state_dot[0] = v * cos_psi;
    state_dot[1] = v * sin_psi;
    state_dot[2] = omega;
}

#endif
