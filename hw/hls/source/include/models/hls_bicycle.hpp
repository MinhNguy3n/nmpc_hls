#ifndef HLS_BICYCLE_HPP
#define HLS_BICYCLE_HPP

// Kinematic bicycle model (RC car) for the PSO-NMPC evaluator (BICYCLE_CONFIG): x' = v cos(psi),
// y' = v sin(psi), psi' = v kappa, about the rear-axle midpoint (docs/ackermann/ackermann_mpc_pso_model.md
// section 3; control [v, kappa], section 4). It is models/hls_unicycle.hpp with psi' = v kappa in
// place of psi' = omega, so System::one_step_prediction (RK4, hls_system.hpp) uses it unchanged:
// the October note's Stage A (section 5.5). The simulated controller predicted with the chord
// step (Stage B); app/rc_car/hls_bicycle_check.py measures what the difference does to the cost.
//
// - Controls arrive normalized to +-100 and are mapped by multiplications only (no division):
//   v = v_min + (v_max - v_min)/200 * (z_v + 100), kappa = kappa_max/100 * z_kappa, so z_v = -100
//   gives v = 0 exactly in half precision (a stop command predicts standstill).
// - cos(psi) is local_sin(psi + pi/2), as in hls_sniffbot.hpp; local_cos is not used (model note
//   10.1: with USE_FAST_SIN_COS it scales the angle twice).
// - Every #pragma HLS sits on its own line: the engine's pipelined copy is generated by deleting
//   the pragma lines (gen_headers.sh), and nothing else may differ.
// - The constants between the BEGIN/END markers are generated from the RC car parameter files by
//   app/rc_car/gen_bicycle_config.py (kappa_max = tan(delta_max)/L); do not edit them by hand.

#include "hls_arith_aux_functions.hpp"
#ifdef __SYNTHESIS__
#include "hls_math.h"
#include "ap_fixed.h"
using namespace hls;
#else
#include "math.h"
#endif

template <
    typename _model_real
>void __model(
    volatile _model_real *state_dot, // [3]
    volatile _model_real *state,     // [3]
    volatile _model_real *control    // [2]
){

#pragma HLS interface mode=ap_fifo port=state_dot   depth=3
#pragma HLS interface mode=ap_fifo port=state       depth=3
#pragma HLS interface mode=ap_fifo port=control     depth=2

    // BEGIN generated constants (app/rc_car/gen_bicycle_config.py)
    // SIMULATION values: v in [0, 2] m/s (v_max_sim), kappa_max = tan(0.356)/0.275 = 1.35215627744 1/m
    const _model_real v_min = 0.0;              // m/s
    const _model_real z_v_min = -100;          // normalized control at v_min
    const _model_real v_per_unit = 0.01;        // (v_max - v_min) / 200   [m/s per unit]
    const _model_real kappa_per_unit = 0.013521562774403716; // kappa_max / 100   [1/m per unit]
    // END generated constants
    const _model_real local_pi_half = 1.57079632679;

#pragma HLS allocation operation instances=hmul limit=4
#pragma HLS allocation operation instances=hadd limit=2
#pragma HLS allocation operation instances=hsub limit=2

    _model_real psi, v, kappa, cos_psi, sin_psi;

    psi = state[2];
    v = v_min + v_per_unit * (control[0] - z_v_min);
    kappa = kappa_per_unit * control[1];

    cos_psi = local_sin<_model_real>(psi + (_model_real)local_pi_half);
    sin_psi = local_sin<_model_real>(psi);

    state_dot[0] = v * cos_psi;
    state_dot[1] = v * sin_psi;
    state_dot[2] = v * kappa;
}

#endif
